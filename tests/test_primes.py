import pytest
from collections import Counter
from primes import prime_fact_decomp


@pytest.mark.parametrize(
    "n, exp_decomp",
    [
        (1, Counter({1: 1})),
        (10, Counter({2: 1, 5: 1})),
        (
            12255577675769874796353741423233529747545733723912224783376315779968120256056086360115960212061364135373543000,
            Counter(
                {
                    2: 3,
                    3: 3,
                    5: 3,
                    7: 3,
                    11: 3,
                    13: 3,
                    17: 3,
                    19: 3,
                    23: 3,
                    29: 3,
                    31: 3,
                    37: 3,
                    41: 3,
                    43: 3,
                    47: 3,
                    53: 3,
                    59: 3,
                    61: 3,
                    67: 3,
                    71: 3,
                    73: 3,
                    79: 3,
                    83: 3,
                    89: 3,
                    97: 3,
                }
            ),
        ),
        (
            23894069338082822379993847357955006185493595069916229217767700000,
            Counter(
                {
                    0: 1,
                    2: 5,
                    3: 5,
                    5: 5,
                    7: 5,
                    11: 5,
                    13: 5,
                    17: 5,
                    19: 5,
                    278292080125497995703445849373: 1,
                }
            ),
        ),
        (
            5734554439708490114031658404432851684081770978434160110398994779661281138551245330000000000,
            Counter(
                {2: 10, 3: 10, 5: 10, 7: 10, 11: 10, 13: 10, 17: 10, 19: 10, 9196877: 3}
            ),
        ),
    ],
)
def test_prime_fact_decomp(n, exp_decomp):
    decomp = prime_fact_decomp(n)
    assert decomp == exp_decomp
